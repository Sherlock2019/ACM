"""ACM scene engine: a situation as a structured script, its consequences, and next scenes.

    load_scene(id_or_path)        read + validate a scene file (scenes/<id>.yaml)
    timeline(scene)               the state before and after every event
    DemoProvider / ModelProvider  analysis and branches (authored, or generated by a local LLM)
    select_branch(scene, id)      a branch with its timeline and scene directions
    directions(scene, branch)     the acm.directions/1 export for players and future engines
    bundle(scene)                 everything the dashboard needs, as one JSON-ready dict
"""

from __future__ import annotations

from pathlib import Path
from typing import Any

import yaml

from acm.scene.directions import check_directions, directions
from acm.scene.providers import DemoProvider, ModelProvider, ProviderError, generate_branches, get_provider
from acm.scene.schema import (
    DIRECTIONS_SCHEMA, SCENE_SCHEMA, VERBS, Analysis, Branch, Consequence, Event, Scene, Source, Status,
)
from acm.scene.state import branch_timeline, final_state, initial_state, timeline
from acm.scene.validate import SceneError, validate_branch, validate_scene

SCENES_DIR = Path(__file__).resolve().parents[3] / "scenes"


def scene_ids() -> list[str]:
    return sorted(p.stem for p in SCENES_DIR.glob("*.yaml"))


def load_scene(ref: str | Path) -> Scene:
    path = Path(ref)
    if not path.suffix:
        path = SCENES_DIR / f"{ref}.yaml"
    if not path.is_file():
        raise FileNotFoundError(f"no scene file {path} (known scenes: {', '.join(scene_ids()) or 'none'})")
    data = yaml.safe_load(path.read_text(encoding="utf-8"))
    return validate_scene(Scene.model_validate(data))


def select_branch(scene: Scene, branch_id: str, branches: list[Branch] | None = None) -> dict[str, Any]:
    pool = branches if branches is not None else DemoProvider().branches(scene)
    branch = next((b for b in pool if b.id.lower() == branch_id.lower()), None)
    if branch is None:
        raise KeyError(f"no branch {branch_id!r} (available: {', '.join(b.id for b in pool)})")
    return {"branch": branch, "timeline": branch_timeline(scene, branch), "directions": directions(scene, branch)}


def bundle(scene: Scene) -> dict[str, Any]:
    """The scene, its states, the demo analysis, the authored branches and their directions."""
    demo = DemoProvider()
    analysis = demo.analyze(scene)
    branches = demo.branches(scene)
    return {
        "schema": SCENE_SCHEMA,
        "generated_by": "acm.scene (DemoProvider: authored, deterministic)",
        "scene": scene.model_dump(mode="json", by_alias=True, exclude={"demo"}),
        "timeline": timeline(scene),
        "analysis": analysis.model_dump(mode="json"),
        "branches": [
            {**b.model_dump(mode="json"), "timeline": branch_timeline(scene, b), "directions": directions(scene, b)}
            for b in branches
        ],
        "directions": directions(scene),
        "vocabulary": VERBS,
    }


