"""Ask ACM about an action: MLM reads the question, ACM answers in Phrase DNA.

    action (+ context) --MLM--> frame --ACM--> report
    question           --MLM--> question frame --> intent + subjects it names
    answer             = the report's consequences for those subjects, each one written
                         as its own phrase: WHO · DOES · WHAT · WHERE · WHEN · WITH WHOM · WHY,
                         chained to the original action (action -> consequence)

"What if ...?" questions run ACM again on the hypothetical clause, with the same
context, and report what changes against the original. Every answer row comes from
the engine's report; nothing is generated by a language model.
"""

from __future__ import annotations

import re
from typing import Any

from acm.engine import ConsequenceEngine
from acm.inference import DIRECTION_WORDS, LAYER_NAMES, STATUS_WORDS, _name, _why, answers
from acm.schema import Consequence, ConsequenceReport, Relation, RelationStatus, Target

RING_TITLES = {
    Target.ACTOR: "Actor", Target.IMPACTED: "Impacted", Target.OTHER_ACTORS: "Other actors",
    Target.ENVIRONMENT: "Local environment", Target.NEIGHBOUR: "Neighbours", Target.ORGANIZATION: "Organization",
    Target.CITY: "City", Target.COUNTRY: "Country", Target.SOCIETY: "Society", Target.EARTH: "Earth",
}

#: Words in a question that point at a ring rather than at a named subject.
RING_WORDS: dict[Target, set[str]] = {
    Target.NEIGHBOUR: {"neighbour", "neighbours", "neighbor", "neighbors", "nearby", "near", "around", "residents"},
    Target.ORGANIZATION: {"organization", "organisation", "company", "companies", "business", "businesses",
                          "enterprise", "institution", "institutions", "employer", "firms", "insurer", "insurers"},
    Target.CITY: {"city", "town", "municipality", "urban"},
    Target.COUNTRY: {"country", "nation", "national", "state", "government"},
    Target.SOCIETY: {"society", "economy", "public", "law", "trust", "everyone", "community"},
    Target.EARTH: {"earth", "planet", "climate", "nature", "emissions", "carbon", "biodiversity", "environment"},
}
SELF_WORDS = {"i", "me", "my", "myself", "model", "you"}
HARM_WORDS = {"harm", "harmed", "hurt", "hurts", "lose", "loses", "lost", "suffer", "suffers", "damage",
              "damaged", "victim", "victims", "worse", "bad", "negative", "pay", "cost"}
HELP_WORDS = {"help", "helped", "helps", "benefit", "benefits", "gain", "gains", "win", "wins", "better",
              "good", "positive"}
WH_WORDS = ("who", "whom", "what", "where", "when", "why", "how", "which", "will", "does", "do", "did",
            "is", "are", "can")
STOP = {"the", "a", "an", "to", "of", "in", "on", "at", "for", "by", "with", "and", "or", "next", "then",
        "happen", "happens", "happened", "will", "would", "does", "do", "did", "is", "are", "be", "what",
        "who", "whom", "where", "when", "why", "how", "which", "it", "this", "that", "after", "now", "get",
        "gets", "affected", "affect", "affects", "change", "changes", "can"}
IF_CLAUSE = re.compile(r"^\s*(?:and\s+)?(?:what\s+(?:would\s+happen|happens|will\s+happen)?\s*if|what\s+if|"
                       r"suppose(?:\s+that)?|imagine(?:\s+that)?|if)\s+(?P<clause>.+?)\s*[?.!]*\s*$", re.I)
PLACE_STATES = {"at", "in", "on", "near"}
HARMFUL = {RelationStatus.BLOCKED, RelationStatus.HINDERED, RelationStatus.AT_RISK}
HELPFUL = {RelationStatus.ADVANCED, RelationStatus.ENABLED}


def _words(text: str) -> list[str]:
    return re.findall(r"[a-z0-9']+", text.lower().replace("'s", ""))


def _texts(frame: dict[str, Any], *slots: str) -> str | None:
    found = [e["text"] for slot in slots for e in frame.get(slot, [])]
    return ", ".join(found) or None


# -- the meaning of the action and of the question ----------------------------------------

def action_dna(report: ConsequenceReport) -> dict[str, Any]:
    """The original action as Phrase DNA, from the frame ACM used."""
    frame = report.trace.get("frame", {})
    return {
        "text": report.action_text,
        "who": "I (the model)" if report.self_view else report.actor_label,
        "does": report.predicate,
        "concept": report.concept,
        "what": _texts(frame, "objects"),
        "to_whom": _texts(frame, "recipients"),
        "with_whom": _texts(frame, "participants", "instrument"),
        "where": ", ".join(report.places) or _texts(frame, "location"),
        "from_where": _texts(frame, "source"),
        "when": _texts(frame, "time") or report.tense,
        "how": _texts(frame, "manner"),
        "why": _texts(frame, "goal", "cause"),
        "condition": report.condition,
        "negated": not report.realized,
        "certainty": report.certainty,
    }


def question_dna(question: str, pipeline: Any) -> dict[str, Any]:
    """MLM's reading of the question itself: its wh-word, predicate and filled slots."""
    words = _words(question)
    wh = next((w for w in words[:3] if w in WH_WORDS), None)
    out: dict[str, Any] = {"text": question, "wh": wh, "parsed": False, "predicate": None, "slots": [],
                           "tense": None, "negated": False, "note": None}
    try:
        analysis = pipeline.analyze(question, language="en", detect_style=False)
    except Exception as exc:  # noqa: BLE001 - the answer still works from the words
        out["note"] = f"MLM could not parse the question ({exc}); matched on its words"
        return out
    if not analysis.frames:
        out["note"] = "MLM produced no frame for the question; matched on its words"
        return out
    frame = analysis.frames[-1]
    out["parsed"] = True
    out["predicate"] = frame.predicate.lemma if frame.predicate else None
    out["tense"] = frame.tense.value if frame.tense else None
    out["negated"] = frame.negation
    out["slots"] = [{"slot": slot, "text": e.text, "role": e.semantic_role, "head": e.head_lemma}
                    for slot, e in frame.elements()]
    return out


def _intent(question: str, words: list[str], wh: str | None) -> str:
    if IF_CLAUSE.match(question):
        return "what_if"
    if wh == "why" or "because" in words or "reason" in words:
        return "why"
    if wh in {"who", "whom"} or {"whom", "anyone", "someone", "everybody", "people"} & set(words[:4]):
        return "who"
    if wh == "where" or {"reach", "spread", "far"} & set(words):
        return "where"
    if wh == "when":
        return "when"
    if wh == "how" and words[1:2] and words[1] in {"sure", "certain", "likely", "confident"}:
        return "certainty"
    return "subject"


# -- consequences as phrases ----------------------------------------------------------------

def _when(report: ConsequenceReport) -> str:
    if report.condition:
        return f"only if {report.condition}"
    return {"past": "after the action (it happened)", "future": "if it happens (planned)"}.get(
        report.tense or "", "after the action")


def _chain(c: Consequence, report: ConsequenceReport, dna: dict[str, Any]) -> dict[str, Any]:
    """One consequence written as its own phrase, chained to the action that causes it."""
    because = f"because: {report.action_text.rstrip('.')}"
    if c.fact is not None:
        state, labels = c.fact.state, c.fact.labels
        kind = "action" if state == "occurs_at" else "status"
        verb = f"is {state}" if state in PLACE_STATES else state.replace("_", " ")
        phrase = {
            "who": "I" if c.about == "self" else c.about_label,
            "does": ("" if c.fact.value else "no longer ") + verb,
            "what": ", ".join(lbl for lbl in labels if lbl != c.about_label) or None,
            "where": dna["where"] if c.target != Target.ENVIRONMENT else c.about_label,
            "with_whom": ", ".join(lbl for lbl in labels[2:]) or None,
        }
    else:
        kind = "impact"
        from acm.render import layer_extent

        extent = layer_extent(report, c.target)
        phrase = {
            "who": extent if extent and extent not in {"not known", "no place stated"} else LAYER_NAMES.get(c.target, c.target.value),
            "does": f"{c.about} {DIRECTION_WORDS.get(c.direction or '0')}",
            "what": c.text,
            "where": extent or LAYER_NAMES.get(c.target),
            "with_whom": None,
        }
    return {
        "ring": c.target.value, "ring_title": RING_TITLES[c.target], "subject": c.about_label, "key": c.about,
        "kind": kind, "text": c.text, "basis": c.basis if c.informative else "generic", "direction": c.direction,
        "certainty": c.certainty,
        "dna": {**phrase, "when": _when(report), "why": because, "rule": _why(c, report)},
    }


def _relation_chain(r: Relation, report: ConsequenceReport, dna: dict[str, Any]) -> dict[str, Any]:
    owner = _name(r.intention.owner_label)
    own = r.intention.owner == report.actor
    return {
        "ring": (Target.ACTOR if own else Target.OTHER_ACTORS).value,
        "ring_title": "Actor" if own else "Other actors",
        "subject": r.intention.owner_label, "key": r.intention.owner, "kind": "goal",
        "text": f"{r.intention.text.rstrip('.')}: {r.status.value}", "basis": "rule", "status": r.status.value,
        "direction": "+" if r.status in HELPFUL else "-" if r.status in HARMFUL else "0",
        "certainty": report.certainty,
        "dna": {"who": owner, "does": f"{'goal' if r.intention.kind == 'goal' else 'earlier action'} {STATUS_WORDS[r.status]}",
                "what": r.intention.text.rstrip("."), "where": None, "with_whom": None, "when": _when(report),
                "why": f"because: {report.action_text.rstrip('.')}", "rule": r.reason},
    }


def chains(report: ConsequenceReport) -> list[dict[str, Any]]:
    dna = action_dna(report)
    out = [_chain(c, report, dna) for c in report.consequences]
    out += [_relation_chain(r, report, dna) for r in report.relations]
    order = list(RING_TITLES)
    return sorted(out, key=lambda ch: order.index(Target(ch["ring"])))


def _unknowns(report: ConsequenceReport) -> list[dict[str, Any]]:
    return [{"subject": u.about_label, "aspect": u.aspect, "text": u.text, "needs": u.needs} for u in report.unknowns]


# -- matching the question to the report ------------------------------------------------------

def _mentions(chain: dict[str, Any], words: set[str], report: ConsequenceReport) -> bool:
    ring = Target(chain["ring"])
    if ring in RING_WORDS and RING_WORDS[ring] & words:
        return True
    if chain["key"] == "self" or (ring == Target.ACTOR and report.self_view):
        if SELF_WORDS & words:
            return True
    names = set(_words(chain["subject"])) - STOP
    return bool(names & words)


def _harmful(ch: dict[str, Any]) -> bool:
    if ch["kind"] == "goal":
        return ch["status"] in {s.value for s in HARMFUL}
    if ch["kind"] == "impact":
        return ch["direction"] == "-"
    return ch["dna"]["does"].startswith("no longer")


def _helpful(ch: dict[str, Any]) -> bool:
    if ch["kind"] == "goal":
        return ch["status"] in {s.value for s in HELPFUL}
    if ch["kind"] == "impact":
        return ch["direction"] == "+"
    return ch["kind"] == "status" and not ch["dna"]["does"].startswith("no longer")


def _answer_text(intent: str, picked: list[dict[str, Any]], report: ConsequenceReport, dna: dict[str, Any],
                 qa: list[dict[str, Any]], words: set[str]) -> tuple[str, list[str]]:
    if not report.realized:
        return (f"Nothing. The sentence says {dna['who']} does not {report.predicate}, so none of the consequences "
                "follow — for anyone.", ["negation in MLM's frame cancels every state change and every effect on goals"])
    if intent == "why":
        if dna["why"]:
            stated = f"The sentence states the reason: {dna['why']} (MLM goal/cause slot)."
        else:
            stated = "The sentence does not say why — the reason is UNKNOWN; ACM does not invent one."
        rules = [ch["dna"]["rule"] for ch in picked][:6]
        return stated + (" Each consequence follows from a rule, listed below." if picked else ""), rules
    if intent == "where":
        places = ", ".join(report.places) or "no place stated"
        reach = sorted({ch["ring_title"] for ch in picked}, key=list(RING_TITLES.values()).index)
        return (f"It happens at {places}. Its effects reach: {', '.join(reach) or 'no wider layer'}.",
                ["places come from MLM's WHERE slots; wider layers from ACM's impact rules"])
    if intent == "when":
        frame_time = dna["when"]
        return (f"When: {frame_time or 'not stated'} (tense {report.tense or 'unknown'}). Consequences hold "
                f"{_when(report)}.", [f"certainty {report.certainty:.2f} is a rule weight from tense/modality/condition"])
    if intent == "certainty":
        return (f"ACM's certainty is {report.certainty:.2f}. It is a rule weight from tense, modality and conditions "
                "— not a probability.", [])
    if intent == "who":
        who = list(dict.fromkeys(_name(ch["subject"]) if ch["kind"] != "impact" else ch["dna"]["who"] for ch in picked))
        tone = "harmed" if HARM_WORDS & words else "helped" if HELP_WORDS & words else "affected"
        if not who:
            return f"ACM finds no one {tone} by this action in its rules (no evidence, not 'no impact').", []
        return f"{tone.capitalize()}: {', '.join(who)}.", [ch["dna"]["rule"] for ch in picked][:6]
    # subject: reuse the inference suite's sentence for each subject ACM matched
    sentences, why = [], []
    keys = {(ch["kind"], ch["subject"]) for ch in picked}
    for a in qa:
        hit = any(
            (a["kind"] == "actor" and k == "status" and _name(s) == a["subject"]) or
            (a["kind"] in {"impacted", "place"} and _name(s) == a["subject"]) or
            (a["kind"] == "goal" and k == "goal" and _name(s) == a["subject"]) or
            (a["kind"] == "layer" and k == "impact" and any(ch["ring"] == a.get("layer") for ch in picked))
            for k, s in keys)
        if hit and a["answer"] not in sentences:
            sentences.append(a["answer"])
            why += a["why"]
    if sentences:
        return " ".join(sentences), why
    return ("ACM's rules say nothing about that here. That is no evidence, not 'no impact'.", report.notes)


def _select(intent: str, all_chains: list[dict[str, Any]], words: set[str], report: ConsequenceReport):
    named = [ch for ch in all_chains if _mentions(ch, words, report)]
    if intent == "where":
        layered = [ch for ch in all_chains if Target(ch["ring"]) in {Target.ENVIRONMENT, *LAYER_NAMES}]
        return named or layered
    if intent == "who":
        pool = named or [ch for ch in all_chains if ch["kind"] != "action"]
        if HARM_WORDS & words:
            return [ch for ch in pool if _harmful(ch)]
        if HELP_WORDS & words:
            return [ch for ch in pool if _helpful(ch)]
        return pool
    if intent in {"why", "when", "certainty"}:
        return named or all_chains
    # subject questions: what the question names; "what happens next?" alone -> everything
    return named if named else (all_chains if not (set(words) - STOP) else [])


def _diff(before: list[dict[str, Any]], after: list[dict[str, Any]]) -> dict[str, list[dict[str, Any]]]:
    key = lambda ch: (ch["ring"], ch["subject"], ch["text"])  # noqa: E731
    old, new = {key(c): c for c in before}, {key(c): c for c in after}
    return {"added": [new[k] for k in new if k not in old], "removed": [old[k] for k in old if k not in new],
            "kept": [new[k] for k in new if k in old]}


def ask(text: str, context: list[str], question: str, pipeline: Any, *,
        engine: ConsequenceEngine | None = None, report: ConsequenceReport | None = None) -> dict[str, Any]:
    """Answer one question about the action, in Phrase DNA, with ACM's reasons."""
    engine = engine or ConsequenceEngine(pipeline=pipeline)
    report = report or engine.analyze(text, context=context)
    if report.predicate is None:
        raise ValueError("; ".join(report.notes) or "MLM found no action in the text")
    q = question_dna(question, pipeline)
    words = _words(question)
    intent = _intent(question, words, q["wh"])
    dna = action_dna(report)
    all_chains = chains(report)
    out: dict[str, Any] = {"question": q, "intent": intent, "action": dna, "unknowns": _unknowns(report)}

    if intent == "what_if":
        clause = IF_CLAUSE.match(question).group("clause").strip()
        clause = clause[:1].upper() + clause[1:] + ("" if clause.endswith(".") else ".")
        alt = engine.analyze(clause, context=context)
        if alt.predicate is None:
            raise ValueError(f"MLM found no action in '{clause}'")
        alt_dna, alt_chains = action_dna(alt), chains(alt)
        diff = _diff(all_chains, alt_chains)
        if not alt.realized:
            answer = f"Then nothing follows: '{clause}' is negated, so all {len(all_chains)} consequences of the original disappear."
        else:
            answer = (f"ACM re-ran the action as '{clause}' ({alt.predicate} → {alt.concept or 'no concept'}): "
                      f"{len(diff['added'])} new consequence(s), {len(diff['removed'])} no longer follow, "
                      f"{len(diff['kept'])} stay the same.")
        out |= {"answer": answer, "why": [f"same context, new action parsed by MLM: {clause}", *alt.notes],
                "chains": alt_chains, "counterfactual": {"text": clause, "action": alt_dna, **diff}}
        return out

    picked = _select(intent, all_chains, set(words), report)
    answer, why = _answer_text(intent, picked, report, dna, answers(report), set(words))
    out |= {"answer": answer, "why": why, "chains": picked}
    return out


def suggestions(report: ConsequenceReport) -> list[str]:
    """Questions this report can answer: one per subject, plus why / who / what-if."""
    qs = [a["question"] for a in answers(report) if a["kind"] not in {"limits", "none"}][:5]
    who = "I" if report.self_view else report.actor_label
    qs += ["Who is harmed?", "Why?", "Where do the effects reach?"]
    if who and report.predicate and report.realized:
        qs.append(f"What if {who} did not {report.predicate}?")
    return list(dict.fromkeys(qs))
