"""Draw docs/blast-radius.svg: ARM's radius of consequences as eight concentric rings.

    python scripts/draw_blast_radius.py

The eight rings group the engine's layers for presentation; each legend row names the layer(s)
it shows and what ARM reports there for the README's example sentence. No dependencies.
"""

from __future__ import annotations

from html import escape
from pathlib import Path

OUT = Path(__file__).resolve().parent.parent / "docs" / "blast-radius.svg"
INK = "#0b1b2e"

# (title, subtitle, fill, engine layers, what ARM reports for the example)
RINGS = [
    ("ACTOR", "Goals, resources and immediate outcomes", "#e0e7ff", "self",
     "loses my car · gains money · own goal 'pay my debt': ENABLED"),
    ("OTHER PARTICIPANTS", "People affected, their goals and possible reactions", "#dbeafe", "impacted · other actors",
     "Sarah gains my car · Mark's goal BLOCKED · Sarah's need ADVANCED"),
    ("LOCAL PHYSICAL WORLD", "Objects, surroundings and immediate environment", "#cffafe", "local environment",
     "Paris: the sale takes place here"),
    ("NEIGHBOURHOOD", "Nearby people, places and community", "#ccfbf1", "neighbour",
     "Boulogne-Billancourt, Saint-Denis, Montreuil: no known impact"),
    ("CITY / REGION", "Local services, infrastructure and institutions", "#dcfce7", "organization · city",
     "insurers and the vehicle registry record the new owner"),
    ("SOCIETY", "Social norms, trust and collective behaviour", "#fef9c3", "society",
     "money circulates through the economy"),
    ("ECONOMY & COUNTRIES", "Markets, organisations and national effects", "#fde68a", "country",
     "France: a taxable transaction counts in national activity"),
    ("THE WORLD", "Cross-border, global and planetary effects", "#fed7aa", "earth",
     "an existing car is reused instead of a new one being made"),
]


def svg() -> str:
    width, height = 1240, 900
    cx, cy, core = 380, 515, 46
    step = (330 - core) / len(RINGS)
    out = [
        f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {width} {height}" width="{width}" height="{height}" '
        'font-family="Inter, Segoe UI, Helvetica, Arial, sans-serif">',
        f'<rect width="{width}" height="{height}" rx="18" fill="#f8fafc"/>',
        '<text x="40" y="52" font-size="15" font-weight="700" letter-spacing="2" fill="#0891b2">ACTION–REACTION MODEL</text>',
        f'<text x="40" y="98" font-size="40" font-weight="800" fill="{INK}">The radius of consequences</text>',
        '<text x="40" y="130" font-size="18" fill="#475569">One action can create effects across people, places and systems.</text>',
        '<text x="40" y="158" font-size="16" fill="#0e7490">Example: “I will sell my car to Sarah in Paris tomorrow to pay my debt.”'
        '  (Mark wants to buy my car. Sarah needs a car.)</text>',
    ]
    for i in range(len(RINGS), 0, -1):
        fill = RINGS[i - 1][2]
        out.append(f'<circle cx="{cx}" cy="{cy}" r="{core + step * i:.1f}" fill="{fill}" stroke="#ffffff" stroke-width="3"/>')
    for i in range(1, len(RINGS) + 1):
        y = cy - (core + step * i) + step / 2 + 6
        out.append(f'<text x="{cx}" y="{y:.1f}" text-anchor="middle" font-size="16" font-weight="700" fill="{INK}">{i}</text>')
    out.append(f'<circle cx="{cx}" cy="{cy}" r="{core - 4}" fill="{INK}" stroke="#ffffff" stroke-width="3"/>')
    out.append(f'<text x="{cx}" y="{cy + 5}" text-anchor="middle" font-size="14" font-weight="800" letter-spacing="1" fill="#ffffff">ACTION</text>')

    x, y0, row = 770, 250, 78
    for i, (title, sub, fill, layers, example) in enumerate(RINGS):
        y = y0 + i * row
        out.append(f'<circle cx="{x}" cy="{y}" r="14" fill="{fill}" stroke="#cbd5e1"/>')
        out.append(f'<text x="{x}" y="{y + 5}" text-anchor="middle" font-size="14" font-weight="700" fill="{INK}">{i + 1}</text>')
        out.append(f'<text x="{x + 28}" y="{y - 6}" font-size="16" font-weight="800" fill="{INK}">{escape(title)}'
                   f'<tspan font-size="12" font-weight="500" fill="#64748b">  · layer: {escape(layers)}</tspan></text>')
        out.append(f'<text x="{x + 28}" y="{y + 13}" font-size="13.5" fill="#475569">{escape(sub)}</text>')
        out.append(f'<text x="{x + 28}" y="{y + 31}" font-size="12.5" font-style="italic" fill="#0e7490">→ {escape(example)}</text>')
    out.append(f'<text x="40" y="{height - 22}" font-size="13" fill="#64748b">"No known impact" means no rule matched, '
               'never that there is no impact. Generated by scripts/draw_blast_radius.py.</text>')
    out.append("</svg>")
    return "\n".join(out) + "\n"


if __name__ == "__main__":
    OUT.write_text(svg(), encoding="utf-8")
    print(f"wrote {OUT}")
